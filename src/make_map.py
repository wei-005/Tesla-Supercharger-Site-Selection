"""Step 8: browser map. Writes web/sites.js from the final site table and the Tesla network, for web/index.html.

    python src/make_map.py      then open web/index.html in a browser (no server needed)
"""
import json
import pandas as pd
from config import ROOT, OUT, PROC

WEB = ROOT / "web"
WEB.mkdir(exist_ok=True)
SHOW_STATUS = {"OPEN": "open", "EXPANDING": "open", "CLOSED_TEMP": "open",
               "CONSTRUCTION": "pipeline", "PERMIT": "pipeline", "PLAN": "pipeline"}


# map label per cell: Chinese name, English name, callout offset (px) from the marker; dx<0 label on the left,
# dx=0 centred below/above, dx>0 on the right
CITY = {
    "86283631fffffff": ("斯托克顿", "Stockton, CA", -28, -38),
    "8629a0c47ffffff": ("温彻斯特", "Winchester, CA", 0, 50),
    "8629b6d37ffffff": ("菲尼克斯", "Phoenix, AZ", 26, 42),
    "86268c60fffffff": ("科罗拉多泉", "Colorado Springs, CO", 28, 0),
    "862a100afffffff": ("纽约布朗克斯", "Bronx, NY", 28, -4),
    "86441a597ffffff": ("奥本代尔", "Auburndale, FL", 28, 8),
    "8628f0137ffffff": ("俄勒冈城", "Oregon City, OR", -28, -6),
    "8629a970fffffff": ("洛斯巴诺斯", "Los Banos, CA", -28, 34),
    "862ab2ce7ffffff": ("底特律", "Detroit, MI", 28, -34),
    "862a94d07ffffff": ("托莱多", "Toledo, OH", -28, 38),
}


def main():
    T = pd.read_csv(OUT / "final_10_sites.csv")
    sites = []
    for _, r in T.iterrows():
        cn, en, dx, dy = CITY.get(r["H3_res6"], (r["县"], f'{r["县"]}, {r["州"]}', 28, 0))
        sites.append(dict(city_cn=cn, city_en=en, dx=dx, dy=dy,
            rank=int(r["排名"]), segment="corridor" if r["类型"] == "高速走廊" else "metro",
            state=r["州"], county=r["县"], host=r["宿主"], address=r["地址"], host_type=r["宿主类型"],
            lat=float(r["纬度"]), lng=float(r["经度"]), cell=r["H3_res6"],
            stalls=int(r["超充桩(V4)"]), trailer=int(r["其中拖挂直通车位"]), l2=int(r["慢充(目的地L2)"]),
            interconnect=r["并网方式"], request_kw=int(r["申请功率_kW"]), megapacks=int(r["Megapack台数"]),
            months=int(r["预计通电_月"]), hours=r["运营时间"], grid=r["电网运行策略"], pricing=r["定价与运营"],
            mwh=int(r["首年服务电量_MWh"]), corridor_mwh=int(r["其中走廊需求_MWh"]), util=float(r["利用率"]),
            capex=int(r["CAPEX_万美元"]), npv=int(r["NPV_万美元"]), comp_share=float(r["竞品需求占比"]),
            d_tesla=float(r["距最近特斯拉站_km(含在建/规划)"]), d_cell=float(r["宿主距网格中心_km"]),
            alternate=r["备选宿主"]))
    sc = pd.read_csv(PROC / "superchargers.csv")
    sc = sc[sc.status.isin(SHOW_STATUS)]
    tesla = [[round(a, 4), round(b, 4), 1 if SHOW_STATUS[s] == "pipeline" else 0, int(n)]
             for a, b, s, n in zip(sc.lat, sc.lng, sc.status, sc.stalls.fillna(0))]
    js = ("// generated by src/make_map.py from outputs/final_10_sites.csv and data/processed/superchargers.csv\n"
          f"window.SITES = {json.dumps(sites, ensure_ascii=False, indent=1)};\n"
          f"// Tesla network: [lat, lng, 0=open 1=construction/permit/plan, stalls]\n"
          f"window.TESLA = {json.dumps(tesla, separators=(',', ':'))};\n")
    (WEB / "sites.js").write_text(js, encoding="utf-8")
    write_basemap()
    print(f"web/sites.js: {len(sites)} sites, {len(tesla)} Tesla sites")


def write_basemap():
    """offline vector basemap (state + neighbour-country outlines) drawn under the tiles; shows when tiles can't load"""
    from geo import load_topo, features

    def gj(topo, obj, keep):
        feats = []
        for props, _, polys in features(load_topo(topo), obj):
            if not keep(props, polys):
                continue
            coords = [[[[round(a, 3), round(b, 3)] for a, b in r] for r in p] for p in polys]
            feats.append({"type": "Feature", "properties": {"n": props.get("name", "")},
                          "geometry": {"type": "MultiPolygon", "coordinates": coords}})
        return {"type": "FeatureCollection", "features": feats}
    na = lambda props, polys: props.get("name") != "United States of America" and any(
        p[0][:, 0].max() > -170 and p[0][:, 0].min() < -50 and p[0][:, 1].max() > 5 for p in polys)
    data = {"countries": gj("countries-110m.json", "countries", na),
            "states": gj("states-10m.json", "states", lambda p, g: True)}
    (WEB / "basemap.js").write_text("// generated by src/make_map.py (US Census / Natural Earth outlines)\nwindow.BASEMAP = "
                                    + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")


if __name__ == "__main__":
    main()
